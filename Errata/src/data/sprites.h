// -----------------------------------------------------------------------------
//  sprites.h - THE UI CHROME AND THE BODY LOOKUP. NOT AN ATLAS ANY MORE.
//
//  WHAT IS IN HERE: the 12x12 action icons, the 8x8 meter icons, the 12x12
//  genome badges, the twelve emotes, the SpritePose vocabulary, the flash
//  budget over all of the art, and - below the LOOKUP banner - the hand-written
//  logic that turns a Bug into a SpriteRef. All of it hand-typed, none of it
//  generated, and that is now stated once instead of being contradicted.
//
//  WHAT IS NOT: the creature art. `enum SpriteSetId`, `SPRITE_SETS` and the 38
//  Nottamagochi body and pose sets were deleted at P9-C3. The atlas is
//  data/sprites_bugs.h - 64 sets of 24x24x2, generated by tools/gen_sprites.py
//  from tools/sprites/*.txt, gated by `gen_sprites.py --check` in
//  tools/check.sh - and this file includes it.
//
//  THIS BANNER USED TO LIE, AND THE LIE IS WORTH KEEPING A PARAGRAPH FOR.
//  It said "GENERATED FILE - DO NOT HAND EDIT. Source of truth:
//  scratchpad/sprite_src.py. Regenerate with: python sprite_src.py". THAT FILE
//  HAS NEVER EXISTED IN THIS REPOSITORY - `git log --all` over all 77 commits
//  found no trace of it, scratchpad/ is not in the tree and is not even in
//  .gitignore, and ui/petfx.cpp:13 and ui/xbm_mirror.h:19 both already said so
//  out loud. tools/check.sh had no rule for this file either, so 9.4 KB of art
//  was labelled generated, its generator was unreachable, and nothing checked it
//  in either direction. An instruction that cannot be followed is worse than no
//  instruction: it tells the next reader their edit will be overwritten, when in
//  fact nothing ever will. P9-C1 wrote the generator that was missing and P9-C3
//  moved the art onto it.
//
//  Format: XBM - see data/sprite_types.h, which owns the stride/bit-order/frame
//  contract and the two size-guard macros. Feed straight to
//  u8g2.drawXBM(x, y, w, h, bits).
//  All arrays are `inline constexpr` so the linker keeps ONE copy in .rodata
//  (flash) no matter how many translation units include this header.
// -----------------------------------------------------------------------------
