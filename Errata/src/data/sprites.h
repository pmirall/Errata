// THE ART REVISION, DERIVED (P9-C3). It was `#define SPRITE_REV 1` with a
// comment telling a human to bump it on any art change, and a number a human is
// supposed to bump is a number that does not get bumped - this file's own
// SPRITE_DATA_BYTES was wrong by 144 B for two phases for exactly that reason.
// ER_SPRITE_ART_HASH is FNV-1a over every emitted byte, every set's dimensions,
// the set ORDER and the eye bands, folded to 16 bits by tools/gen_sprites.py, so
// it moves when the art moves and it cannot be forgotten. The DIAG page
// (ui.cpp) prints it; the browser caches sprite blobs by (id, rev).
