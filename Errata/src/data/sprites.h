// -----------------------------------------------------------------------------
//  THE ART BUDGET - MEASURED BY THE COMPILER, NOT TYPED BY A HUMAN
//
//  THIS USED TO BE `#define SPRITE_DATA_BYTES 10623` GUARDED BY
//  `static_assert(SPRITE_DATA_BYTES <= 24576)`, WHICH IS A COMPARISON OF TWO
//  LITERALS. It could not fail from an art change, and it had already failed to:
//  the number was correct at d21f20f^ and P4-C6 then deleted spr_mood12 (6 x
//  12x12 = 144 B) without touching it, so it over-stated the atlas by exactly
//  144 B for two phases while the assert stayed green. P9-C1 made it walk the
//  real arrays through the real tables. This file now owns TWO tables' worth of
//  art - the generated atlas it includes, and the icons/mini-icons/badges/emotes
//  that were never part of the swap - and counts both.
//
//  THE 24,576 CEILING IS GONE, AND THAT IS THE POINT OF THIS CHUNK. It was a
//  TRANSITION allowance sized for the one moment both rosters were in the tree
//  at once (peak 10,479 + 8,640 = 19,119 B). Both rosters are no longer in the
//  tree: the 36 legacy body and pose sets are deleted. An allowance left
//  standing after the thing it allowed for is a budget that has stopped meaning
//  anything, so the number below is the END STATE plus a stated margin:
//
//      generated atlas   9,216 B   2 eggs + SLEEP + SICK + 60 bodies, all
//                                  24x24x2 at 144 B (data/sprites_bugs.h,
//                                  ER_SPRITE_DATA_BYTES_DECLARED)
//      survivors         1,031 B   spr_icon12 384 + spr_mini8 168 +
//                                  spr_badge12 312 + the 12 emotes 167
//                                  (CORRECTED AT P9-C6: this line read "96" and
//                                  "239", which are wrong by +/-72 B and cancel,
//                                  so the total was right and neither term was.
//                                  spr_mini8 is MIC_COUNT = 21 icons x 8 B; 96
//                                  would be twelve. The test below now asserts
//                                  the four TERMS and not only their sum, which
//                                  is what let two wrong numbers sit next to a
//                                  passing assertion in three files.)
//      END STATE        10,247 B   = SPRITE_DATA_BYTES_DECLARED below
//      margin            1,017 B   SEVEN more 24x24x2 sets (1,008 B): one more
//                                  three-stage family and four effect sets,
//                                  which is what P9-C5's corruption glitch and
//                                  P10's animation pass could plausibly want
//      MAX              11,264 B   the two, rounded up to 11 KiB
//
//  That is 0.70 % of the 1,600,000 B RELEASE flash cap and 4.1 % of the 273,600 B
//  the release variant had spare at 37511d5. Both halves name the same variant
//  now: the sentence used to quote 0.47 % of GATE_FLASH_MAX (2,400,000), which
//  check.sh polices on the BASELINE build, beside a number derived from
//  GATE_RELEASE_FLASH_MAX - the two-caps confusion docs/decisions.md already has
//  a paragraph correcting. A roster that grows past it is not a
//  budget failure to absorb, it is a re-plan: 21 families would need this number
//  raised and said out loud, which is exactly the conversation 24,576 was
//  swallowing.
// -----------------------------------------------------------------------------
constexpr unsigned sprite_atlas_bytes() {
  unsigned n = pb_sprite_atlas_bytes();
  for (unsigned i = 0; i < (unsigned)EMO_COUNT; ++i)
    n += spr_xbm_bytes(SPRITE_EMOTES[i].w, SPRITE_EMOTES[i].h);
  return n + (unsigned)sizeof(spr_icon12) + (unsigned)sizeof(spr_mini8)
           + (unsigned)sizeof(spr_badge12);
}

#define SPRITE_DATA_BYTES          (sprite_atlas_bytes())
#define SPRITE_DATA_BYTES_DECLARED 10247u
#define SPRITE_DATA_BYTES_MAX      11264u

static_assert(SPRITE_DATA_BYTES == SPRITE_DATA_BYTES_DECLARED,
              "the atlas changed size - re-measure SPRITE_DATA_BYTES_DECLARED "
              "and say so in the commit (tools/check.sh cannot see art)");
static_assert(SPRITE_DATA_BYTES <= SPRITE_DATA_BYTES_MAX,
              "sprite art over the flash budget");

// -----------------------------------------------------------------------------
//  LOOKUP
//
//  EVERYTHING FROM HERE TO THE END OF THE FILE IS HAND-WRITTEN LOGIC, not art.
//  The art is data/sprites_bugs.h, generated from tools/sprites/*.txt.
//
//  WHAT P9-C3 DID TO THIS BLOCK, AND WHAT IT COST.
//
//  ONE BODY PER SPECIES. sprite_design_of() is gone. It folded an art key with
//  `% 8` at BABY and `% 6` at ADULT/SENIOR because the atlas authored 8 baby
//  bodies and 6 adult ones for 36 species; the atlas now authors 60, one per
//  roster id, at ER_SPRITE_BODY_FIRST + (id - 1). `form` IS the art key.
//
//  THE STAGE NO LONGER CHANGES THE BODY, and that is a real deletion, not a
//  refactor. A Bug's silhouette is its species at every stage from BABY to
//  SENIOR. What used to carry growth - blob -> child -> teen -> 40x40 adult ->
//  32x32 senior - is now carried by the ROSTER instead: a family's three
//  species ARE its three stages (species.json `stage` 0/1/2), they evolve into
//  one another, and each has its own drawing. So growth is still on screen; it
//  is on screen once per family instead of five times per pet.
//
//  THE CARE-QUALITY BODY IS DELETED. sprite_form_of() used to read minor_form
//  at CHILD and TEEN to pick SPR_CHILD_GOOD vs SPR_CHILD_POOR - the care
//  quality frozen when the pet grew. One body per species has nowhere to put
//  it: a "descuidado" variant would be a 61st..120th drawing. The parameter is
//  gone from the signature rather than ignored, so every call site had to be
//  visited; tests/test_pet_view.cpp records the deletion and pins the rule that
//  replaced it. Whoever wants care quality back on HOME should draw it with the
//  renderer (a sweat emote, a dulled dither) and not with a second atlas.
//
//  THE POSE QUESTION, ANSWERED. The legacy atlas had SEVEN pose sets - SLEEP at
//  four sizes, SICK and EAT at three. There are now TWO, both 24x24:
//
//    SLEEP  ONE generic body, 144 B. SLEEP is a STATE: pet_pose_of() returns it
//           from the sim, it persists, and HOME has to show it on the STILL
//           path (ui/screen_home.cpp), which is the only body path a host test
//           or a golden can see. Per-species sleepers would be 60 x 144 =
//           8,640 B more and 60 more drawings.
//    SICK   ONE generic body, 144 B, for the same reason: pet_pose_of() returns
//           POSE_SICK from PF_SICK, so it is a state and not a film.
//    EAT    NO ART AT ALL. POSE_EAT is reachable ONLY from actfx_pose() during
//           the two-second feeding film (ui/actfx.cpp); pet_pose_of() never
//           returns it, no golden has ever recorded it, and the renderer
//           already parks EMO_BOWL against the body's measured ink wall and can
//           lean the body with petfx_squash(). So POSE_EAT falls through to the
//           species body and the film carries the pose. COST, stated: the
//           authored "leaning over the bowl" silhouette is gone, and what
//           replaces it lives in ui/actfx.cpp + ui/petfx.cpp, which are
//           device-only translation units no host binary compiles. That is the
//           one place this chunk moves behaviour into a layer the suite cannot
//           see, and it is the pose that was already invisible to it.
//
//  IDENTITY LOSS ON SLEEP AND SICK IS INHERITED, NOT INTRODUCED. The old
//  sprite_set_id() ignored `form` in every pose branch, so a sleeping BABY_GATO,
//  BABY_SETA, BABY_PEZ and BABY_ROBOT were already the same blob. What changed
//  is the count (7 sets -> 2) and the size (24, 28, 32 and 40 px -> 24), not
//  whether a species keeps its face while it sleeps. It does not, and it did
//  not.
// -----------------------------------------------------------------------------

// The half-open window of set ids that are CREATURE BODIES. Everything outside
// it is an egg or a pose, and a species that resolves onto one of those is not
// being drawn - it is being mistaken for furniture. game/species.cpp asserts
// the whole roster against it at compile time and tests/test_content.cpp
// re-checks it at runtime.
#define SPRITE_BODY_FIRST  ((uint8_t)ER_SPRITE_BODY_FIRST)
#define SPRITE_BODY_LAST   ((uint8_t)(ER_SPRITE_BODY_FIRST + ER_SPRITE_BODY_COUNT - 1))
#define SPRITE_SET_COUNT   ((uint8_t)ER_SPRITE_SET_COUNT)

// -----------------------------------------------------------------------------
//  sprite_form_of(art_key, stage) - THE ONLY correct source of `form`.
//
//  `form` is the art key for every stage that has a body, and 0 for an egg
//  (an egg is an egg). `art_key` is ui/pet_art.h's pet_art_key(): the SPECIES
//  row's sprite_id when the Bug has a row, and the genome's species nibble
//  when it has none.
//
//  THE minor_form PARAMETER WENT WITH THE CARE-QUALITY BODIES - see the banner
//  above. It is not ignored, it is absent, so a call site that still had
//  something to say about it is a compile error rather than a silent no-op.
// -----------------------------------------------------------------------------
// data/ may not depend on game/, so this takes the decoded key rather than the
// live view it comes from.
constexpr uint8_t sprite_form_of(uint8_t art_key, Stage stage) {
  return (stage == STAGE_EGG) ? (uint8_t)0 : art_key;
}

// Map a live pet onto an animation set id.
//   stage : enum Stage.
//   form  : sprite_form_of() output - the species' art key.
//   pose  : enum SpritePose. POSE_EAT falls through to the body on purpose.
//
// THE CLAMP IS NOT DECORATION. `form` can reach here from a saved nibble a
// future save format widened, or from a species row a newer build wrote, and an
// unclamped add would index straight past ER_SPRITE_SETS into whatever follows
// it. Out of range falls back to the first body, never past the end.
//
// =============================================================================
//  THE THREE POSE BRANCHES BELOW WERE DECIDED AT P10-C3, NOT LEFT. Read this
//  before changing one of them; each is a different answer for a different
//  reason, and "they are all shared" stopped being true.
//
//  POSE_SLEEP - STILL RETURNS THE SHARED BODY HERE, AND ALMOST NOTHING USES IT.
//  Sleep is DERIVED at draw time since P10-C3: ui/petfx_core.cpp's
//  pf_build_sleep() takes the species' own idle frame, shuts its eyes with the
//  blink's own pf_build_lids(), merges its two topmost ink rows and splays its
//  bottom four, and BOTH of HOME's body paths call it - ui/screen_home.cpp's
//  still one and ui/petfx.cpp's animated one. So a sleeping Bug keeps its
//  silhouette, which on HOME is the only thing distinguishing it from anyone
//  else's, and the change is measured: 13 px on the quietest body in the roster
//  (ESTATIC) against a floor of 10, asserted over all 120 (species, frame) pairs
//  in tests/test_sprite_pipeline.cpp.
//    WHY THE BRANCH SURVIVES ANYWAY: pf_build_sleep() refuses a blank frame or
//  one wider than the cache geometry, and this is what the caller falls back
//  to. No body in today's atlas takes that path - the sweep says so by name -
//  and the 144 B stays because it is the safety net under a derivation, in
//  exactly the spirit of the clamp two lines down. Deleting it would also mean
//  regenerating the atlas and moving ER_SPRITE_BODY_FIRST, which is a re-plan
//  for 144 B.
//
//  POSE_SICK - GENUINELY SHARED, AND THAT IS THE DECISION RATHER THAN THE
//  LEFTOVER. Every cheap derivation is already spoken for or already known bad:
//  the squash is the SLEEP pose and also the landing and the yawn; an erase
//  dither is gene_pattern, and ui/petfx.cpp's PF_PAT_LEVEL banner records that
//  anything at or above level 3 combs a body into a venetian blind; a one-row
//  shear on the upper half is a new shape rule applied to sixty drawings by
//  five hands, and NO INSTRUMENT IN THIS REPOSITORY CAN TELL "slumped" FROM
//  "broken" - only a person can, one body at a time. So SICK keeps the generic
//  body, and the identity loss is real and is being accepted rather than
//  denied. THE OWNER STEP, priced: author twenty family sick bodies (one per
//  family, 20 x 144 = 2,880 B), raise ER_SPRITE_DATA_BYTES_MAX in
//  tools/gen_sprites.py AND SPRITE_DATA_BYTES_MAX above, and review them with
//  `./bin/sprite_dump text NAME`. The atlas has 1,024 B free, so twenty sets do
//  NOT fit and this is a re-plan of both caps, said out loud.
//
//  POSE_EAT - NOT A GAP, AND THE TREE ALREADY PROVED IT. It falls through to
//  the species body on purpose and the FILM carries the pose: ui/actfx.cpp
//  lunges the whole silhouette at the bowl, dips it on the bite and parks the
//  bowl against the body's measured ink wall. tests/test_screens.cpp pins
//  eat_diff == 0 on HOME with the comment "so 'we dropped it' cannot decay into
//  'we forgot it'". P10-C3 looked at it again and changed nothing.
// =============================================================================
constexpr uint8_t sprite_set_id(uint8_t stage, uint8_t form, uint8_t pose) {
  if (stage == (uint8_t)STAGE_EGG) return (uint8_t)BUGSPR_EGG_IDLE;
  if (pose  == (uint8_t)POSE_SLEEP) return (uint8_t)BUGSPR_SLEEP;
  if (pose  == (uint8_t)POSE_SICK)  return (uint8_t)BUGSPR_SICK;
  return (uint8_t)(ER_SPRITE_BODY_FIRST
                   + (form < (uint8_t)ER_SPRITE_BODY_COUNT ? form : (uint8_t)0));
}

inline SpriteSet sprite_set(uint8_t id) {
  if (id >= (uint8_t)ER_SPRITE_SET_COUNT) id = (uint8_t)BUGSPR_EGG_IDLE;
  return ER_SPRITE_SETS[id];
}

inline SpriteRef sprite_frame(uint8_t id, uint8_t frame) {
  const SpriteSet s = sprite_set(id);
  // `stride` here is BYTES PER FRAME, not the row stride - the two differ and
  // pf_stride(w) three files away means the other one.
  const uint16_t stride = (uint16_t)(((s.w + 7u) >> 3) * s.h);
  if (frame >= s.frames) frame = (uint8_t)(frame % s.frames);
  SpriteRef r = { s.bits + (uint32_t)stride * frame, s.w, s.h };
  return r;
}

// Pose-aware body lookup.
inline SpriteRef sprite_lookup_pose(uint8_t stage, uint8_t form,
                                    uint8_t pose, uint8_t frame) {
  return sprite_frame(sprite_set_id(stage, form, pose), frame);
}

// The blink band for one set and frame, in UNMIRRORED sprite space. Generated
// beside the pixels; { 255, 0, 0, 0 } means this body does not blink.
inline SpriteEyeBand sprite_eyes(uint8_t id, uint8_t frame) {
  if (id >= (uint8_t)ER_SPRITE_SET_COUNT) id = (uint8_t)BUGSPR_EGG_IDLE;
  if (frame > 1u) frame = (uint8_t)(frame & 1u);
  return ER_SPRITE_EYES[id][frame];
}

inline SpriteRef sprite_egg(uint8_t phase, uint8_t frame) {
  return sprite_frame(phase ? (uint8_t)BUGSPR_EGG_CRACK : (uint8_t)BUGSPR_EGG_IDLE, frame);
}

inline SpriteRef sprite_icon(uint8_t id) {
  if (id >= ICO_COUNT) id = 0;
  SpriteRef r = { spr_icon12 + (uint16_t)id * 24u, 12, 12 };
  return r;
}

inline SpriteRef sprite_mini(uint8_t id) {
  if (id >= MIC_COUNT) id = 0;
  SpriteRef r = { spr_mini8 + (uint16_t)id * 8u, 8, 8 };
  return r;
}

// Indexed by the species gene; 12..15 render the UNKNOWN badge.
// SPRITE_BADGE_COUNT is defined next to spr_badge12, with its size guard.
inline SpriteRef sprite_species_badge(uint8_t species) {
  if (species >= SPRITE_BADGE_COUNT) species = SPRITE_BADGE_COUNT - 1;
  SpriteRef r = { spr_badge12 + (uint16_t)species * 24u, 12, 12 };
  return r;
}

inline SpriteRef sprite_emote(uint8_t id) {
  if (id >= EMO_COUNT) id = 0;
  return SPRITE_EMOTES[id];
}

// Nominal draw origin that centres a body sprite inside the sprite area.
inline uint8_t sprite_center_x(uint8_t w) { return (uint8_t)((OLED_W - w) / 2); }
inline uint8_t sprite_center_y(uint8_t h) {
  return (uint8_t)(SPRITE_AREA_Y + (SPRITE_AREA_H > h ? (SPRITE_AREA_H - h) / 2 : 0));
}

